"""CZ-Z's tables (firmware/src/eng_cz.c) -> build/gen/cz_tables.h. Standard library only.

CZ_COS[0x800]: the uPD933's cosine, exactly as MAME's upd933_device::device_start builds m_cosine (Devin Acker,
BSD-3-Clause): 0xfff * (1 - cos(2 pi i / 0x7ff)) / 2, truncated to an integer. tests/cz_ref.cpp checks it against
MAME's own table, value for value.

CZ_RATE[100]: the CZ-style 8-step envelope's speed (eng_cz.c cz_env8), not the chip's: the CZ's firmware, not its
sound chip, turns a panel rate 0..99 into the chip's steps, and that firmware is Casio's. So a rate here is our own
curve: a full sweep (level 0 -> 99) takes 20 s * 2^(-r / 7) (rate 0: 20 s, 50: ~0.14 s, 99: ~1.1 ms), as an increment
per 44.1 kHz sample of a level held as level << 16. Tuned by ear, not measured.
"""
import math
import sys

FS = 44100


def main(out):
    cos = [int(0xfff * (1 - math.cos(2.0 * math.pi * i / 0x7ff)) / 2) for i in range(0x800)]
    rate = []
    for r in range(100):
        t = 20.0 * 2.0 ** (-r / 7.0)
        rate.append(max(1, int(round((99 << 16) / (t * FS)))))
    h = ["/* generated by tools/gen_cz_tables.py: do not edit (CZ-Z, firmware/src/eng_cz.c) */",
         "static const uint16_t CZ_COS[0x800] = {"]
    for k in range(0, 0x800, 16):
        h.append("    " + ", ".join(str(v) for v in cos[k:k + 16]) + ",")
    h += ["};", "static const uint32_t CZ_RATE[100] = {"]
    for k in range(0, 100, 10):
        h.append("    " + ", ".join(f"{v}u" for v in rate[k:k + 10]) + ",")
    h.append("};")
    open(out, "w", encoding="utf-8").write("\n".join(h) + "\n")
    print(f"cz tables: CZ_COS 4096 B, CZ_RATE 400 B -> {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/cz_tables.h")
