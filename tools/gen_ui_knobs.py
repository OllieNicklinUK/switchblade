"""The rack UI's knob caps (ui_rack.c): a conical brushed gunmetal cap seen from above, no pointer (the cap is the same
at every angle; the pointer is drawn over it). One bitmap per size, rendered 4 x 4 supersampled.

  gen_ui_knobs.py OUT.h

Output: for each diameter D in SIZES
  KCAP<D>_C   uint16_t RGB565 per pixel (rows back to back)
  KCAP<D>_A   uint8_t coverage 0..16 per pixel (0: off the cap)
"""
import math
import sys

SIZES = (14, 18, 28, 34)
SS = 4


def noise(i):
    """a fixed hash, 0..1"""
    i = (i * 2654435761) & 0xFFFFFFFF
    i ^= i >> 15
    i = (i * 0x2C1B3C6D) & 0xFFFFFFFF
    i ^= i >> 12
    return (i & 0xFFFF) / 65535.0


def shade(x, y):
    """the cap at (x, y), radius 1: (r, g, b) 0..1"""
    r = math.hypot(x, y)
    th = math.atan2(y, x)
    # the cone's two highlights (light from the upper left and its mirror), a soft fall between them
    spec = max(0.0, math.cos(2.0 * (th + 2.3))) ** 3
    side = 0.5 + 0.5 * math.cos(th + 2.3)                 # the lit half
    # the brushing: fine radial streaks (by the angle), stronger toward the rim
    b = int((th + math.pi) / (2 * math.pi) * 720)
    br = (noise(b) - 0.5) * 0.07 + (noise(b // 3 + 9000) - 0.5) * 0.05
    lum = 0.20 + 0.10 * side + 0.42 * spec + br * (0.4 + 0.6 * r)
    if r < 0.16:                                          # the centre: a small flat spot
        lum = 0.26 + 0.06 * side
    if r > 0.86:                                          # the bevel: dark, a lit edge on the upper left
        edge = (r - 0.86) / 0.14
        lum = lum * (1.0 - 0.55 * edge) + 0.18 * max(0.0, math.cos(th + 2.3)) * (1.0 - edge)
    lum = min(1.0, max(0.0, lum))
    return (lum * 0.90, lum * 0.95, lum * 1.0)


def cap(d):
    cols, alph = [], []
    rad = d / 2.0
    for py in range(d):
        for px in range(d):
            acc = [0.0, 0.0, 0.0]
            n = 0
            for sy in range(SS):
                for sx in range(SS):
                    x = (px + (sx + 0.5) / SS - rad) / rad
                    y = (py + (sy + 0.5) / SS - rad) / rad
                    if x * x + y * y <= 1.0:
                        c = shade(x, y)
                        acc = [a + v for a, v in zip(acc, c)]
                        n += 1
            if n:
                r, g, b = (min(255, int(round(a / n * 255))) for a in acc)
                cols.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            else:
                cols.append(0)
            alph.append((n * 16 + (SS * SS) // 2) // (SS * SS))
    return cols, alph


def main():
    out = [f"/* generated by tools/gen_ui_knobs.py: the rack's knob caps (ui_rack.c) */",
           "#ifndef UI_KNOBS_H", "#define UI_KNOBS_H"]
    total = 0
    for d in SIZES:
        c, a = cap(d)
        out.append(f"static const uint16_t KCAP{d}_C[{d * d}] = {{")
        out += ["    " + ", ".join(f"0x{v:04X}" for v in c[i:i + 12]) + "," for i in range(0, len(c), 12)]
        out.append("};")
        out.append(f"static const uint8_t KCAP{d}_A[{d * d}] = {{")
        out += ["    " + ", ".join(str(v) for v in a[i:i + 24]) + "," for i in range(0, len(a), 24)]
        out.append("};")
        total += d * d * 3
    out.append("#endif")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"knob caps {SIZES}: {total} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
