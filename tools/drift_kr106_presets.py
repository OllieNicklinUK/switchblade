"""JUNO's presets 33..50 from the Ultramaster KR-106's factory banks (Karl LaRocca, GPL-3.0: its Source/KR106_Presets_JUCE.h,
the Juno-60 tape dump and the Juno-106 factory SysEx; the DRIFT engine is a port of that synth's DSP). 18 keys and leads
(2026-11-19, the user: "focussing on keys and leads"), chosen for what JUNO plays: no noise, no arpeggio, the DCO's pulse,
saw, pulse + saw or saw + sub.

  tools/drift_kr106_presets.py [KR106_DIR]     (default ../ultramaster_kr106-main)

Rewrites the generated block at the end of presets/four/drift.py (between the KR-106 markers) and docs/drift_presets.md.
Real units come from the KR-106's own curves: presets/kr106/kr106_values.txt, made by tools/kr106_values.cpp.

The mapping (eng_drift.c, docs/plans/2026-10-17-drift-juno.md):
  MIX         pulse only 127, saw only 64, pulse + saw 96, saw + sub the MIX law's point of the same sub / saw ratio (lost:
              a sub under the pulse, MIX has no such point)
  PW          with the pulse: PWM MAN -> PW below 64 (64 = 50 %, 0 = 95 %), PWM LFO -> PW above 64 (the auto PWM's depth),
              PWM ENV -> MAN at half the depth (lost: the envelope); else 64
  CUT RES KTR the VCF's Hz on JUNO's display law, RES and KBD 1:1 (C4 the zero, 127 = 1:1, both)
  ENV         A D S R from the KR-106's ms (Felucca's times); ENV -> FLT the VCF ENV as cutoff steps (the KR-106's 10 octaves at
              full), signed by INV; past JUNO's 63 steps the base cutoff is raised by the rest (at most 2 octaves) so the
              envelope's peak stays where it was
  HPF         -> P_FTYPE (J106: boost / flat / 236 / 754 Hz; J60's 122 / 269 / 571 Hz to the nearest)
  LFO         rate (Hz), delay (the fade), DCO LFO (semitones) -> LFO DEST PIT, VCF LFO -> LFO DEST FLT; triangle, free
  chorus      I / II / I+II (DRIFT_PX)
  octave      the octave switch (KR-106 value - 1) -> DRIFT_LX[7] (P_FM4_DEC)
  lost        VCA GATE (the amp follows the envelope too), the VCA level (LEVEL is the track's), portamento (none of these
              18 use it), the bender, the arpeggiator
"""
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_PY = ROOT / "presets" / "four" / "drift.py"
OUT_MD = ROOT / "docs" / "drift_presets.md"
VALUES = ROOT / "presets" / "kr106" / "kr106_values.txt"
DEF_KR = ROOT.parent / "ultramaster_kr106-main"
BEGIN = "# --- KR-106 presets 33..50: GENERATED by tools/drift_kr106_presets.py (do not edit between the markers) ---"
END = "# --- end of the KR-106 presets ---"

# (KR-106 index, category, FM-1 name, pattern): 10 keys, 8 leads
PICK = [
    (142, "KEYS", "E PIANO I", 6), (143, "KEYS", "E PIANO II", 6), (8, "KEYS", "PIANO 60", 3), (76, "KEYS", "CHIME PIANO", 3),
    (72, "KEYS", "CLAV I", 6), (169, "KEYS", "CLAV 106", 6), (10, "KEYS", "CELESTA", 3), (94, "KEYS", "FLAMENCO GTR", 3),
    (201, "KEYS", "NYLON GUITAR", 3), (203, "KEYS", "BRIGHT PLUCK", 3),
    (108, "LEAD", "HAMMER LEAD", 4), (109, "LEAD", "DUKE LEAD", 4), (110, "LEAD", "NEG LEAD", 4), (111, "LEAD", "BLIP LEAD", 4),
    (160, "LEAD", "LEAD I", 4), (162, "LEAD", "LEAD III", 4), (90, "LEAD", "SOLO TRUMPET", 4), (249, "LEAD", "PICCOLO TRMP", 4),
]
FX = dict(KEYS=(0, 10, 20, 30), LEAD=(0, 10, 35, 25))
STEPS_PER_OCT = 127 / math.log2(16000 / 30)          # CUTOFF_HZ: ~14 steps an octave


def clampi(v, lo, hi):
    return int(max(lo, min(hi, round(v))))


def time_knob(ms):
    """Felucca's F_TIME: 1 ms * 10000^(v / 127)"""
    return clampi(127 * math.log10(max(ms, 1.0)) / 4.0, 0, 127)


def cut_index(hz):
    return 127 * math.log(max(hz, 30.0) / 30.0) / math.log(16000 / 30)


def load(kr_dir):
    src = (kr_dir / "Source" / "KR106_Presets_JUCE.h").read_text()
    raw = [(n, [int(t) for t in v.split(",")]) for n, v in re.findall(r'\{"([^"]+)",\s*\{([^}]*)\}\}', src)]
    vals = {}
    for line in VALUES.read_text().splitlines():
        f = line.split("|")
        vals[int(f[0])] = dict(name=f[1], hz=float(f[2]), lfo_hz=float(f[3]), delay=float(f[4]), dco_lfo=float(f[5]),
                               vcf_lfo=float(f[6]), a=float(f[7]), d=float(f[8]), r=float(f[9]))
    if len(raw) != 256 or len(vals) != 256:
        raise SystemExit(f"drift_kr106_presets: {len(raw)} presets / {len(vals)} values, want 256")
    return raw, vals


def convert(k, x, v, cat, name):
    lost, notes = [], []
    j60 = k < 128
    pulse, saw = x[23], x[24]
    sub = (x[7] / 127) if (x[7] and (x[25] or not j60)) else 0.0
    if x[8] > 5:
        raise SystemExit(f"{name}: uses noise")
    if saw and pulse:
        mix = 96
        if sub:
            lost.append("sub under pulse + saw")
    elif saw:
        mix = clampi((3584 + 384 * sub) / (56 + 48 * sub), 8, 64) if sub else 64
    elif pulse:
        mix = 127
        if sub:
            lost.append("sub under the pulse")
    else:
        mix = 0
    pw = 64
    if pulse:
        mode = x[33] - 1                                  # -1 LFO, 0 MAN, 1 ENV
        if mode < 0:
            pw = clampi(64 + x[6] / 2, 64, 127)
            notes.append("PWM LFO as the auto PWM")
        elif mode == 0:
            pw = clampi(64 * (1 - x[6] / 127), 0, 64)
        else:
            pw = clampi(64 * (1 - x[6] / 254), 0, 64)
            lost.append("PWM by the envelope (a fixed width)")
    oct_env = (x[12] / 127) * 10.0 * (-1 if x[34] else 1)
    steps = oct_env * STEPS_PER_OCT
    raise_ = 0.0
    if steps > 63:
        raise_ = min(steps - 63, 2 * STEPS_PER_OCT)
        notes.append(f"VCF ENV {oct_env:.1f} oct: base +{raise_ / STEPS_PER_OCT:.1f} oct")
    elif steps < -64:
        lost.append(f"VCF ENV {oct_env:.1f} oct (-4.5 here)")
    fenv = clampi(steps, -64, 63)
    cut = clampi(cut_index(v["hz"]) + raise_, 0, 127)
    env = [time_knob(v["a"]), time_knob(v["d"]), x[18], min(time_knob(v["r"]), 112)]
    if time_knob(v["r"]) > 112:                           # (a voice must end: 4 s at most, the health check's 12 s)
        notes.append(f"release {v['r'] / 1000:.1f} s as 4 s")
    if x[35]:
        lost.append("VCA GATE (the amp follows the envelope)")
    hpf = x[9]
    ftype = {0: 1, 1: 0, 2: 2, 3: 3}[hpf] if not j60 else {0: 0, 1: 2, 2: 2, 3: 3}[hpf]
    lx = [ftype, 0, 0, 0, 0, 0, 0, (x[29] - 1 + 3) if x[29] != 1 else 0]   # the octave switch: KR-106's value - 1
    if v["dco_lfo"] > 0.005 or v["vcf_lfo"] > 0.005:
        lx[1:5] = [1, clampi(127 * math.log(max(v["lfo_hz"], 0.05) / 0.05) / math.log(800), 0, 127), 1,
                   time_knob(v["delay"]) if v["delay"] > 1 else 0]
        lx[5] = clampi(v["dco_lfo"] * 63 / 11.8, 0, 63) or (1 if v["dco_lfo"] > 0.005 else 0)
        lx[6] = clampi(v["vcf_lfo"] * STEPS_PER_OCT / 12, 0, 63)
    chor = (1 if x[27] else 0) + (2 if x[28] else 0)
    if x[29] != 1:
        notes.append(f"octave {x[29] - 1:+d}")
    p = dict(name=name, cat=cat, e=[mix, pw, 20, 8, cut, x[11], 0, x[14]], env=env, fenv=fenv, mono=0, fx=FX[cat], chor=chor,
             lx=lx)
    return p, lost, notes


def main():
    kr = Path(sys.argv[1]) if len(sys.argv) > 1 else DEF_KR
    raw, vals = load(kr)
    out, rep = [], []
    for k, cat, name, pat in PICK:
        n, x = raw[k]
        p, lost, notes = convert(k, x, vals[k], cat, name)
        p["pat"] = pat
        out.append(p)
        rep.append((k, n, p, lost, notes))
    s = OUT_PY.read_text()
    block = [BEGIN, "# 18 keys and leads from the Ultramaster KR-106's factory banks (Karl LaRocca, GPL-3.0); lx = DRIFT_LX", "KR106 = ["]
    block += ["    " + repr(p) + "," for p in out]
    block += ["]", "PRESETS += KR106", END]
    if BEGIN in s:
        s = s[:s.index(BEGIN)] + "\n".join(block) + s[s.index(END) + len(END):]
    else:
        old = "PRESETS += placeholder(PRESETS[:18], 32)"
        if old not in s:
            raise SystemExit("drift_kr106_presets: neither the markers nor the placeholder line in drift.py")
        s = s.replace(old, "\n".join(block))
    OUT_PY.write_text(s if s.endswith("\n") else s + "\n", newline="\n")
    M = ["# JUNO presets 33-50: the Ultramaster KR-106's keys and leads", "",
         "Generated by `tools/drift_kr106_presets.py` from the KR-106's factory banks (`Source/KR106_Presets_JUCE.h`: the",
         "Juno-60 tape dump and the Juno-106 factory SysEx), in real units from its own curves (`tools/kr106_values.cpp`).",
         "JUNO is a port of the KR-106's voice. Per preset: what the conversion approximates (notes) and lost.", "",
         "| # | JUNO | KR-106 preset | Category | Notes | Lost |", "|---|---|---|---|---|---|"]
    for i, (k, n, p, lost, notes) in enumerate(rep):
        bank = "Juno-60" if k < 128 else "Juno-106"
        M.append(f"| {33 + i} | {p['name']} | {n} ({bank}) | {p['cat']} | {'; '.join(notes) or '-'} | {'; '.join(lost) or '-'} |")
    OUT_MD.write_text("\n".join(M) + "\n", newline="\n")
    print(f"drift_kr106_presets: {len(out)} presets -> {OUT_PY.relative_to(ROOT)}, report {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
